#!/usr/bin/env python3
"""Copy only needed HGI rules verbatim from reviewed, pinned NDS SCSS.

Optional maintenance, not part of deployment. --source must point at
_sass/_hgiRoundedStroke.scss from upstream commit
0da6366911e039d5f1afd749a9b116e67dade15d. No Sass/npm build dependency.
Regenerate after adding hgi-* markup; static/browser checks catch missing names.
"""
import argparse
import hashlib
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent.parent
SOURCE_SHA256 = 'd7a8191265d7886833e1d6a06f89cffcb00ae70f229fca5e87e8db5bcebeaa43'
# The optional NDS accessibility panel creates these HGI classes dynamically.
# Reviewed in _js/nds-accessibility.js at the same source commit.
DYNAMIC = {
    'arrow-all-direction', 'text-smallcaps', 'glasses', 'link-04', 'pause',
    'text-align-left', 'paragraph-spacing', 'letter-spacing', 'text-kerning',
    'flash', 'color-picker', 'blur', 'sparkles', 'droplet', 'colors',
}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, required=True)
    args = parser.parse_args()
    data = args.source.read_bytes()
    if hashlib.sha256(data).hexdigest() != SOURCE_SHA256:
        raise SystemExit('Unexpected HGI source; review the upstream version before generating')
    source = data.decode('utf-8-sig')
    base = re.search(r'\.hgi-stroke \{[^}]+\}', source).group(0)
    rules = {
        m.group(2): m.group(1)
        for m in re.finditer(r'(\.hgi-stroke\.hgi-([\w-]+):before \{[^}]+\})', source)
    }
    wanted = set(DYNAMIC)
    for name in ('index.html', 'en/index.html', '404.html', 'assets/js/site.js'):
        # Negative lookbehind excludes nds-hgi-* (SVG masks, not font glyphs).
        wanted.update(re.findall(r'(?<![\w-])hgi-([\w-]+)', (ROOT / name).read_text()))
    wanted.discard('stroke')
    missing = wanted - rules.keys()
    if missing:
        raise SystemExit('Unknown HGI names: ' + ', '.join(sorted(missing)))
    header = ('/*! NDS/Hugeicons MIT — selected canonical rules, not a modified font.\n'
              ' * Source: mazin-musleh/NDS-vanilla 0da6366911e039d5f1afd749a9b116e67dade15d\n'
              ' * Generated by tools/build_hgi.py; see assets/licenses/NDS-vanilla-MIT.txt */\n')
    output = ROOT / 'assets/css/hgi-rounded-stroke-min.css'
    output.write_text(header + base + '\n\n' + '\n\n'.join(rules[n] for n in sorted(wanted)) + '\n')
    print(f'Copied {len(wanted)} complete canonical HGI rules ({output.stat().st_size} bytes); font unchanged')


if __name__ == '__main__':
    main()
